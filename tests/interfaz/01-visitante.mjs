import { abrir, ir, q, qa, txt, chk, resumen, wait, esperar, escribir, clic } from './ayuda.mjs';
console.log('INICIO'); let w = await abrir('/');
chk(txt(w, 'h1') === 'Mochilas para cada aventura', 'hero visible');
chk(qa(w, '#destacadas .prod').length === 4, '4 destacadas');
chk(qa(w, '.faq-item').length === 6, '6 preguntas frecuentes');
chk(txt(w, '.anuncio').includes('$999'), 'barra de envío gratis');
chk(qa(w, '.cat').length === 3, '3 categorías');
// sección de video: portada limpia, un solo título y tres videos cortos alineados
chk(q(w, '.video-main img')?.getAttribute('src') === '/img/home/video-portada.jpg' && qa(w, '.vm-tit').length === 1 && txt(w, '.vm-tit') === 'Míralas en acción', 'video: portada limpia con un solo título');
chk(qa(w, '.mini-video').length === 3 && qa(w, '.mini-video img').every((i) => /\/img\/home\/mini-/.test(i.getAttribute('src'))), 'video: 3 videos cortos con miniaturas limpias');
chk(qa(w, '.mini-txt b').map((b) => b.textContent).join('|') === 'Mochila de viaje compacta|Estilo urbano|Aventura en la montaña', 'video: títulos de los videos cortos');
chk(qa(w, '.video-grid a[target=_blank]').every((a) => a.rel.includes('noopener')), 'video: enlaces externos en pestaña nueva y seguros');
console.log('CATÁLOGO'); await ir(w, '/catalogo');
chk(qa(w, '#resultado .prod').length === 8, `8 mochilas (hay ${qa(w, '#resultado .prod').length})`);
chk(qa(w, '.prod.agotado').length === 1, 'una agotada');
chk(txt(w, '.etq.agot') === 'Agotado', 'etiqueta Agotado');
chk(qa(w, '.etq').some((e) => e.textContent.includes('Solo quedan 3')), 'etiqueta pocas piezas');
chk(txt(w, '#v-min') === '$99' && txt(w, '#v-max') === '$799', `rango de precio ${txt(w, '#v-min')}–${txt(w, '#v-max')}`);
escribir(w, q(w, '#f-q'), 'dino'); await wait(900);
chk(qa(w, '#resultado .prod').length === 1, 'búsqueda "dino" → 1 resultado');
console.log('DETALLE'); await ir(w, '/producto/3');
chk(txt(w, 'h1').startsWith('Mochila verde de dinosaurios'), 'detalle de la mochila de dinosaurios');
chk(qa(w, '.swatch').length === 2, '2 colores');
chk(txt(w, '.precio-g').includes('$599') && txt(w, '.precio-g').includes('IVA incluido'), 'precio con IVA incluido');
chk(qa(w, '.resena').length === 4, '4 reseñas');
chk(qa(w, '.verificado').length === 4, 'insignia Verificado');
chk(txt(w, '.res-prom b') === '4.8', `promedio 4.8 (${txt(w, '.res-prom b')})`);
console.log('CARRITO (visitante)');
clic(w, q(w, '#btn-agregar')); await wait(500);
chk(txt(w, '#contador-carrito') === '1', 'contador = 1');
const inp = q(w, '[data-combo] input'); escribir(w, inp, '-3'); inp.dispatchEvent(new w.Event('blur')); await wait(100);
chk(inp.value === '3', `"-3" se limpia a solo dígitos: ${inp.value}`);
escribir(w, inp, '0'); inp.dispatchEvent(new w.Event('blur')); await wait(100);
chk(inp.value === '1', 'cero → 1');
escribir(w, inp, '99'); inp.dispatchEvent(new w.Event('blur')); await wait(100);
chk(inp.value === '10', `99 → máximo 10 (${inp.value})`);
await ir(w, '/carrito');
chk(txt(w, '.linea h3') === 'Mochila verde de dinosaurios', 'línea en el carrito');
chk(txt(w, '.envio-barra').includes('$400.00'), `aviso envío gratis: ${txt(w, '.envio-barra')}`);
chk(txt(w, '.resumen .total') .includes('$599.00'), 'total $599.00');
chk(txt(w, '.resumen').includes('$82.62'), 'IVA incluido $82.62');
clic(w, q(w, '#btn-comprar')); await esperar(w);
chk(w.location.pathname === '/registro' && w.location.search.includes('volver=%2Fcarrito'), `sin sesión → ${w.location.pathname}${w.location.search}`);
resumen();
