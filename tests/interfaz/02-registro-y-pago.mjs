import { abrir, ir, q, qa, txt, chk, resumen, wait, esperar, escribir, clic } from './ayuda.mjs';
const llenar = (w, f, d) => { for (const [k, v] of Object.entries(d)) { const el = f.querySelector(`[name=${k}]`); if (el.type === 'checkbox') { el.checked = v; el.dispatchEvent(new w.Event('change', { bubbles: true })); } else escribir(w, el, v); } };
const enviar = async (w, f) => { f.dispatchEvent(new w.Event('submit', { bubbles: true, cancelable: true })); await wait(700); };

console.log('REGISTRO'); let w = await abrir('/catalogo');
// visitante agrega la mochila rosa de flores desde la tarjeta
clic(w, q(w, '[data-agregar="1"]')); await wait(500);
chk(txt(w, '#contador-carrito') === '1', 'visitante agregó desde la tarjeta');
await ir(w, '/carrito'); clic(w, q(w, '#btn-comprar')); await esperar(w);
let f = q(w, '#contenido form');
chk(q(w, '#btn-crear').getAttribute('aria-disabled') === 'true', 'Crear cuenta deshabilitado sin aceptar privacidad');
llenar(w, f, { nombres: 'Elizabeth', apellido_paterno: 'Navarro', apellido_materno: 'Duarte', correo: 'ELIZABETH.NAVARRO@example.com', password: 'Clave1234', acepta_privacidad: true });
await enviar(w, f);
chk(txt(w, '.campo.con-error .error').includes('ya está registrado'), 'correo duplicado (sin distinguir mayúsculas)');
chk(!!q(w, '.campo.con-error .error a[href^="/login"]'), 'enlace "Inicia sesión" junto al error');
chk(q(w, '[name=nombres]').value === 'Elizabeth', 'se conservan los demás datos');
chk(q(w, '[name=password]').value === '', 'se limpia la contraseña');
llenar(w, f, { nombres: 'L4', correo: 'mal', password: '123' }); await enviar(w, f);
chk(qa(w, '.campo.con-error').length >= 3, 'errores por campo (nombre, correo, contraseña)');
llenar(w, f, { nombres: 'Mariana', apellido_paterno: 'Quintero', apellido_materno: 'Lara', correo: 'mariana.q@example.com', password: 'Clave1234' }); await enviar(w, f); await esperar(w);
chk(w.location.pathname === '/carrito', `tras registrarse vuelve al carrito (${w.location.pathname})`);
chk(txt(w, '#btn-cuenta').includes('Hola, Mariana'), 'encabezado: Hola, Mariana');
chk(qa(w, '.linea').length === 1, 'el carrito conservó la mochila');

console.log('ENTREGA');
clic(w, q(w, '#btn-comprar')); await esperar(w);
chk(w.location.pathname === '/checkout/entrega', 'paso de entrega');
chk(qa(w, '.paso').length === 4 && q(w, '.paso.act').textContent.includes('Entrega'), 'stepper de 4 pasos');
chk(q(w, '[name=estado_id]').options.length === 33, 'lista de 32 estados');
clic(w, q(w, '#btn-sig')); await wait(300);
chk(qa(w, '.campo.con-error').length >= 4, 'sin datos: marca cada campo obligatorio');
const edo = [...q(w, '[name=estado_id]').options].find((o) => o.textContent === 'Jalisco').value;
escribir(w, q(w, '[name=estado_id]'), edo); await wait(600);
chk(q(w, '[name=municipio_id]').options.length > 100, `municipios de Jalisco (${q(w, '[name=municipio_id]').options.length - 1})`);
chk(txt(w, '#res').includes('4 a 7 días') && txt(w, '#res').includes('$149.00'), 'envío resto del país $149, 4 a 7 días');
escribir(w, q(w, '[name=municipio_id]'), q(w, '[name=municipio_id]').options[2].value);
escribir(w, q(w, '[name=calle]'), 'Av. Vallarta'); escribir(w, q(w, '[name=colonia]'), 'Americana'); escribir(w, q(w, '[name=cp]'), '44160a');
chk(q(w, '[name=cp]').value === '44160', 'CP solo dígitos');
escribir(w, q(w, '[name=referencias]'), 'Portón negro');
chk(txt(w, '.contador').includes('12/200'), 'contador de referencias');
clic(w, q(w, '#btn-sig')); await esperar(w);
chk(w.location.pathname === '/checkout/pago', 'paso de pago');

console.log('PAGO');
const btn = () => q(w, '#btn-sig');
chk(btn().getAttribute('aria-disabled') === 'true', 'Pagar deshabilitado al inicio');
clic(w, btn()); await wait(300);
chk(qa(w, '.campo.con-error').length >= 3, 'al intentar: marca tarjeta, vencimiento, CVV y políticas');
escribir(w, q(w, '#numero'), '4111111111111111'); chk(q(w, '#numero').value === '4111 1111 1111 1111', 'formato de tarjeta con espacios');
escribir(w, q(w, '#vencimiento'), '1228'); chk(q(w, '#vencimiento').value === '12/28', 'auto "/" en vencimiento');
escribir(w, q(w, '#cvv'), '12'); clic(w, btn()); await wait(300);
chk(txt(w, '.campo.con-error').includes('CVV'), 'CVV de 2 dígitos rechazado');
escribir(w, q(w, '#cvv'), '123'); q(w, '#politicas').checked = true; q(w, '#politicas').dispatchEvent(new w.Event('change', { bubbles: true }));
chk(btn().getAttribute('aria-disabled') === 'false', 'Pagar se habilita con datos válidos');
chk(txt(w, '.dos-col').includes('Av. Vallarta'), 'dirección visible con opción Editar');
clic(w, btn()); await wait(1200); await esperar(w);
chk(/\/checkout\/confirmacion\/\d+/.test(w.location.pathname), `confirmación (${w.location.pathname})`);
chk(txt(w, 'h1') === '¡Pago aprobado!', 'mensaje ¡Pago aprobado!');
chk(/Folio PED-0000\d\d/.test(txt(w, '.tarjeta')), `folio: ${txt(w, '.tarjeta').slice(0, 30)}`);
chk(txt(w, '.tarjeta').includes('$649') , 'producto y total en la confirmación');
chk(txt(w, '#contador-carrito') === '' || q(w, '#contador-carrito').classList.contains('oculto'), 'carrito vacío tras pagar');

console.log('CUENTA');
await ir(w, '/cuenta/pedidos');
chk(qa(w, '.pedido-card').length === 1, '1 pedido');
chk(txt(w, '.pedido-card .pill') === 'Pagado', 'estatus Pagado');
chk(!!q(w, '[data-cancel]'), 'botón Cancelar (aún no enviado)');
chk(!!q(w, 'a[href$="/factura"]'), 'botón Solicitar factura');
await ir(w, '/cuenta/datos');
chk(txt(w, 'h1') === 'Mariana Quintero Lara', 'perfil con nombre completo');
chk(q(w, '#correo').readOnly, 'correo no editable');
chk(qa(w, '.dir-card').length === 1, 'dirección guardada al pagar');
await ir(w, '/cuenta/favoritos'); chk(txt(w, '.vacio h3').includes('no tienes favoritos'), 'favoritos vacío');
resumen();
